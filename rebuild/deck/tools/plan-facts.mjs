const DOUBLERS = [[/\bdying causes a triggered ability\b/i, 'wdymc1'], [/\bentering(?: the battlefield)? causes a triggered ability\b/i, 'wenmc1'],
  [/\btokens? would be created\b/i, 'wtkmt1'], [/\+1\/\+1 counters? would be put\b/i, 'wctm-1'], [/\bwould gain life\b/i, 'wlgm-1']];
const HAND_PAYOFF = /\b(?:for each card in your hand|number of cards in your hand|cards in your hand|equal to the number of cards in (?:your|that player's) hand|maximum hand size)\b/i;

// ---- the Deck Builder's reader, mapped to the same codes (fallback) ----
function readerFacts(c) {
  let out = new Set();
  let r; try { r = rrRead(fromScryfall(c) || {}); } catch { return out; }
  const abs = [].concat(r.abilities || [], ...(r.faces || []).map(f => f.abilities || []));
  for (const a of abs) {
    const t = a.trigger || {}, ev = [t.event].concat(t.also || []), sub = String(t.subject || ''), self = /^~|^this\b/i.test(sub), mine = t.controller !== 'opponent';
    const rep = a.kind === 'spell' || (a.kind === 'triggered' && self && /enters|dies/.test(t.event || '')) ? 'o' : '1';
    if (a.kind === 'triggered') {
      const out0 = out, wr = self && /enters|dies/.test(t.event || '') ? 'o' : '1';
      out = { add: x => out0.add(x + wr) };
      const side = self ? 's' : mine ? 'm' : 't';
      if (ev.includes('enters')) out.add('wen' + side + (self ? '-' : /token/i.test(sub) ? 't' : 'c'));
      if (ev.includes('landfall')) out.add('wlf' + (mine ? 'm' : 't') + 'l');
      if (ev.includes('cast-self')) out.add('wcas-');
      if (ev.includes('cast')) out.add('wca' + side + (/creature spell/i.test(sub) && !/noncreature/i.test(sub) ? 'c' : /instant|sorcery/i.test(sub) ? 'i' : /noncreature/i.test(sub) ? 'n' : '-'));
      if (ev.includes('dies')) out.add('wdy' + (self ? 's' : /opponent/i.test(sub) ? 't' : 'm') + 'c');
      if (ev.includes('sacrifice')) out.add('wsc' + side + '-');
      if (ev.includes('token-created')) out.add('wtk' + side + 't');
      if (ev.includes('discard')) out.add('wdc' + side + '-');
      if (ev.includes('draw')) out.add('wdr' + (t.controller === 'opponent' ? 't' : 'm') + '-');
      if (ev.includes('counters-placed')) out.add('wct' + side + '-');
      if (ev.includes('gain-life')) out.add('wlg' + side + '-');
      if (ev.includes('attacks') || ev.includes('combat-damage-player')) out.add('wat' + (self ? 's' : 'm') + 'c');
      if (ev.includes('to-graveyard')) out.add('wgym-');
      out = out0;
    }
    for (const k of a.cost || []) {
      if (k.sacrifice && !/^~$/.test(k.sacrifice.what || '') && /creature|permanent|artifact/i.test(k.sacrifice.what || '')) { const w = /creature/i.test(k.sacrifice.what) ? 'c' : 'p'; out.add('gscm' + w + '1'); if (w === 'c') out.add('gdymc1'); }
      if (k.discard) out.add('gdcm-1');
    }
    for (const e of [].concat(a.effects || [], ...(a.modes || []))) {
      const who = String(e.who || ''), what = String(e.what || (e.target && e.target.what) || '');
      switch (e.do) {
        case 'create-token': { if (e.forPlayerBind || e.forPlayer || (e.scope && e.scope !== 'you')) break;   // Beast Within: the token is the other player's
        const cr = /creature|\d+\/\d+/i.test(e.token || ''); out.add('gtkm' + (cr ? 't' : 'p') + rep); if (cr) out.add('genmt' + rep); break; }
        case 'draw': out.add(/opponent|each player|target player/i.test(who) ? 'gdra-' + rep : 'gdrm-' + rep); break;
        case 'discard': if (!who || /^you$/i.test(who)) out.add('gdcm-' + rep); break;
        case 'gain-life': out.add('glgm-' + rep); break;
        case 'put-counters': case 'proliferate': if (!e.kind || e.kind === '+1/+1') out.add('gctm-' + rep); break;
        case 'mill': case 'surveil': if (!who || /^you$/i.test(who)) out.add('ggym-' + rep); break;
        case 'bounce': if (/you control|you own/i.test(what)) { out.add('gthm' + whatOf(what) + rep); if (/land/i.test(what)) out.add('glfm-' + rep); } break;
        case 'extra-land': out.add('glfm-' + rep); break;
        case 'search': if (/\bland\b/i.test(what) && /battlefield/i.test(e.to || '')) out.add('glfm-' + rep); break;
        case 'no-max-hand': out.add('ghsm-1'); break;
        case 'sacrifice': if (!who || /^you$/i.test(who)) { const w = /creature/i.test(what) ? 'c' : 'p'; out.add('gscm' + w + rep); if (w === 'c') out.add('gdymc' + rep); } break;
      }
    }
  }
  return out;
}

// ---- one card ----
const ACT = /^([^:"]{1,90}):\s*(.+)$/, IS_KW_LINE = /^[A-Z][a-z' -]+(?: \{[^}]*\}| \d+| [A-Z][a-z]+)*(?: \(.*\))?$/;
let nEngine = 0, nReader = 0, nNone = 0;
function cardFacts(c) {
  const faces = c.card_faces && c.card_faces.length ? c.card_faces.map(f => ({ ...c, ...f, card_faces: undefined })) : [c];
  const eng = new Set(), kw = new Set(), txt = new Set();
  let unread = 0;
  for (const f of faces) {
    const name = f.name || c.name, type = f.type_line || c.type_line || '', text = String(f.oracle_text || '');
    if (!text) continue;
    let def; try { def = scryfallToDefinition({ ...f, name, type_line: type, oracle_text: text, id: 'self' }); } catch { continue; }
    const spell = /\b(?:Instant|Sorcery)\b/.test(type);
    // triggers: wants by probe, gives by compiling the effect
    let trig = []; try { trig = parseTriggeredAbilities(def); } catch {}
    const hits = trig.length ? probeWants(def, trig) : new Map();
    for (const a of trig) {
      const h = hits.get(a.id);
      if (h) for (const x of h) eng.add('w' + x + (/^When (?:this|~|[A-Z])[^,]* (?:enters|dies)\b/.test(a.trigger) && !/^Whenever/.test(a.trigger) ? 'o' : '1'));
      else unread++;
      const rep = /^When\b/.test(a.trigger) || spell ? 'o' : '1';
      let res = null; try { res = compileEffectText(a.effect, { sourceName: name }); } catch {}
      if (!givesOf(res, rep, eng)) unread++;
    }
    for (const id of hits.keys()) if (/^keyword-/.test(id)) for (const x of hits.get(id)) eng.add('w' + x + '1');
    const lines = text.split('\n').map(l => l.replace(/\([^)]*\)/g, '').trim()).filter(Boolean);
    for (const line0 of lines) {
      const line = line0.split(name).join('this permanent');
      if (/^(?:When|Whenever|At)\b|[—-]\s*(?:When|Whenever|At)\b/.test(line)) continue;   // triggers above
      for (const [re, facts] of KW) if (re.test(line)) facts.forEach(x => kw.add(x));
      for (const [re, x] of DOUBLERS) if (re.test(line)) txt.add(x);
      if (HAND_PAYOFF.test(line) && !/no maximum hand size/i.test(line)) txt.add('whsm-1');
      const m = ACT.exec(line);
      if (m && /\{|Sacrifice|Discard|Pay|Tap|Exile|Remove|Return/i.test(m[1])) {
        costGives(m[1], eng);
        let res = null; try { res = compileEffectText(m[2], { sourceName: name }); } catch {}
        if (!givesOf(res, '1', eng)) unread++;
      } else if (spell) {
        let res = null; try { res = compileEffectText(line, { sourceName: name }); } catch {}
        if (!givesOf(res, 'o', eng) && !IS_KW_LINE.test(line)) unread++;
      } else if (!IS_KW_LINE.test(line) && /\byou\b/i.test(line)) {
        let res = null; try { res = compileEffectText(line, { sourceName: name }); } catch {}
        givesOf(res, '1', eng);   // statics such as "You have no maximum hand size"; an unread static is not counted
      }
    }
  }
  // the Deck Builder's reader fills what the game engine did not read
  const rdr = unread ? readerFacts(c) : new Set();
  const all = new Map();
  for (const x of eng) all.set(x, 'e');
  for (const x of kw) if (!all.has(x)) all.set(x, 'k');
  for (const x of rdr) if (!all.has(x) && !all.has(x.slice(0, 5) + (x[5] === '1' ? 'o' : '1'))) all.set(x, 'r');
  for (const x of txt) if (!all.has(x)) all.set(x, 'x');
  if (unread) nReader++; else if (eng.size) nEngine++; else nNone++;
  return all;
}

// only facts a chain reads (engine/plans.js CHAINS, loaded with the Deck Builder's files above)
const CHAINS = vm.runInContext('CHAINS', DB), KEEP = c => CHAINS.some(ch => ch.E.test(c) || ch.P.test(c));
function runSlice(list) {
  const table = {}, bySrc = { e: 0, r: 0, k: 0, x: 0 }, slow = [];
  for (const c of list) {
    const t1 = Date.now(), f = cardFacts(c), dt = Date.now() - t1;
    if (dt > 300) slow.push(c.name + ' ' + dt + ' ms');
    const codes = [...f.keys()].filter(KEEP).sort();
    if (!codes.length) continue;
    const src = codes.map(k => f.get(k)).join('');
    table[c.name] = codes.join('') + (/^e+$/.test(src) ? '' : ':' + src);
    for (const k of codes) bySrc[f.get(k)]++;
  }
  return { table, bySrc, slow, n: [nEngine, nReader, nNone] };
}
