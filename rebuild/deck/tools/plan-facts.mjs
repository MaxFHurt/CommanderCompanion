// ---- the game engine's trigger matcher, probed one event at a time (as triggers.js probeTrigger does, but recording
// which event fired the trigger and whose card caused it) ----
const PT = { c: 'Creature — Human', t: 'Creature — Human', l: 'Land', a: 'Artifact', p: 'Enchantment', i: 'Instant', s: 'Sorcery' };
const PROBES = [   // [event type, want code, which probe kinds, which sides]
  ['enters-battlefield', 'en', 'ctlap', 'smt'], ['spell-cast', 'ca', 'ciapsl', 'smt'], ['dies', 'dy', 'ct', 'smt'], ['sacrificed', 'sc', 'ctap', 'smt'],
  ['token-created', 'tk', 'ta', 'mt'], ['discard', 'dc', 'c', 'mt'], ['draw', 'dr', 'c', 'mt'], ['counter-added', 'ct', 'c', 'sm'], ['life-gained', 'lg', 'c', 'mt'],
  ['attacks', 'at', 'c', 'sm'], ['attackers-declared', 'at', 'c', 'sm'], ['combat-damage-player', 'at', 'c', 'sm'], ['put-into-graveyard', 'gy', 'c', 'mt']
];
function probeWants(def, abilities) {
  const hits = new Map();   // ability id -> Set of codes
  const me = { playerId: 'me', displayName: 'Me', deck: { battlefield: [], graveyard: [], hand: [], exile: [] }, counters: {} };
  const opp = { playerId: 'opp', displayName: 'Opp', deck: { battlefield: [], graveyard: [], hand: [], exile: [] }, counters: {} };
  const defs = { self: { ...def, definitionId: 'self' } };
  // the probe cards carry the creature types and the mana value the triggers name ("another Hero", "mana value 4 or greater"),
  // as triggers.js wideProbeTypes does
  const tt = abilities.map(a => a.trigger).join(' '), words = [...new Set((tt.match(/\b[A-Z][a-z]+\b/g) || []).filter(w => !/^(?:When|Whenever|At|If|You|Your|This|That|Another|The|Each|One|Enchanted|Equipped)$/.test(w) && !String(def.name).includes(w)))].join(' ');
  const mv = +((tt.match(/mana value (\d+) or greater/i) || [])[1] || 3);
  const T = k => (k === 'c' || k === 't') && words ? 'Creature — Human ' + words : k === 'a' && words ? 'Artifact — ' + words : PT[k];
  for (const k of Object.keys(PT)) defs['probe-' + k] = { definitionId: 'probe-' + k, name: 'Probe ' + k, typeLine: T(k), manaValue: mv, power: '1', toughness: '1', colors: [], keywords: [] };
  const game = { players: [me, opp], activePlayerId: 'me', turnNumber: 3, cardDefinitions: defs, stack: [] };
  const selfCard = { instanceId: 'self', definitionId: 'self', controllerId: 'me', counters: {}, triggerFireLedger: {} };
  for (const [type, code, kinds, sides] of PROBES) for (const side of sides) for (const k of (side === 's' ? 'c' : kinds)) {
    const who = side === 't' ? opp : me, src = side === 's' ? 'self' : side === 'm' ? 'mine' : 'theirs';
    selfCard.triggerFireLedger = {};
    me.deck.battlefield = [selfCard]; opp.deck.battlefield = [];
    const probe = { instanceId: src, definitionId: 'probe-' + k, controllerId: who.playerId, counters: { '+1/+1': 1 }, token: k === 't' };
    if (side === 'm') me.deck.battlefield.push(probe); if (side === 't') opp.deck.battlefield.push(probe);
    for (const p of [me, opp]) p.counters = { castThisTurn: [{ typeLine: T(k), colors: [], manaValue: mv }] };
    const event = { type, sourceId: src, controllerId: who.playerId, playerId: who.playerId, ownerId: who.playerId, definitionId: side === 's' ? 'self' : 'probe-' + k,
      typeLine: side === 's' ? def.typeLine : T(k), attackerId: src, attackers: [src], defenders: [who === me ? 'opp' : 'me'], defenderId: who === me ? 'opp' : 'me',
      amount: 2, firstThisTurn: true, to: ['creature', 'player'], counter: '+1/+1', drawNumberThisTurn: 2, token: k === 't', manaValue: mv, batchId: 'probe', played: true,
      destination: 'graveyard', fromZone: 'hand', byKind: 'spell' };
    let rows = [];
    try { rows = collectTriggers(game, event); } catch { continue; }
    for (const r of rows) {
      if (r.sourceId !== 'self') continue;
      let c = code, s = side, w = k === 's' ? 'i' : k;
      if (code === 'en' && k === 'l' && side !== 's') c = 'lf';
      if (code === 'ca') w = k === 'c' ? 'c' : (k === 'i' || k === 's') ? 'i' : 'n';
      if (code === 'en' && side === 's') w = '-';
      if (code === 'ca' && side === 's' && !/^When you cast this spell/i.test(String(abilities.find(a => a.id === r.abilityId)?.trigger || ''))) continue;   // its own casting is any creature spell's
      const set = hits.get(r.abilityId) || new Set(); set.add(c + s + w); hits.set(r.abilityId, set);
    }
  }
  return hits;
}

// ---- gives: the game engine's compiled effects ----
const YOURS = /\byou control\b|\byou own\b|\byour\b/i;
function whatOf(scope) { const s = String(scope || ''); return /\bland\b/i.test(s) ? 'l' : /\bcreature\b/i.test(s) ? 'c' : /\bartifact|enchantment|permanent|nonland\b/i.test(s) ? 'p' : '-'; }
function givesOf(res, rep, out) {
  if (!res || !res.supported) return false;
  const req = new Map((res.requirements || []).map(q => [q.bind, q]));
  let ownExile = '';   // an exile of your own permanent, then "return those cards" (Brago): a blink
  const walk = effs => { for (const e of effs || []) {
    if (!e || typeof e !== 'object') continue;
    const q = req.get(e.bind) || {}, scope = q.scope || q.label || '';
    switch (e.kind) {
      case 'bounce': if (e.bind === 'sourceId' || YOURS.test(scope)) { const w = e.bind === 'sourceId' ? 's' : 'm', what = e.bind === 'sourceId' ? 'p' : whatOf(scope); out.add('gth' + w + what + rep); if (what === 'l') out.add('glfm-' + rep); } break;
      case 'exile': case 'exile-many': if (YOURS.test(scope) && !/graveyard|library|hand/i.test(scope)) ownExile = whatOf(scope) === '-' ? 'p' : whatOf(scope); break;
      case 'return-ids': if (ownExile) { out.add('gflm' + ownExile + rep); out.add('genm' + ownExile + rep); } break;
      case 'flicker': out.add('gflm' + whatOf(scope) + rep); out.add('genm' + whatOf(scope) + rep); break;
      case 'create-token': { if (e.forPlayerBind || e.forPlayer || (e.scope && e.scope !== 'you')) break;   // Beast Within: the token is the other player's
        const cr = /Creature/.test(e.typeLine || ''); out.add('gtkm' + (cr ? 't' : 'p') + rep); if (cr) out.add('genmt' + rep); break; }
      case 'copy-token': out.add('gtkmt' + rep); out.add('genmt' + rep); break;
      case 'draw': out.add(/each-player|target|opponent/.test(e.scope || '') || e.bind ? 'gdra-' + rep : 'gdrm-' + rep); break;
      case 'wheel': case 'discard-hand': out.add('gdcm-' + rep); out.add('gdra-' + rep); break;
      case 'discard': if (!e.bind && /^you$/.test(e.scope || '')) out.add('gdcm-' + rep); break;
      case 'sacrifice': case 'sacrifice-many': if (/^you$/.test(e.scope || 'you')) { const w = /creature/i.test(e.filter || scope) ? 'c' : 'p'; out.add('gscm' + w + rep); if (w === 'c') out.add('gdymc' + rep); } break;
      case 'life': if (e.scope === 'you' && e.deltaSign > 0) out.add('glgm-' + rep); break;
      case 'counter': case 'counter-each': case 'double-counter': case 'proliferate': if (!e.counter || e.counter === '+1/+1') out.add('gctm-' + rep); break;
      case 'mill': case 'surveil': if (!e.scope || e.scope === 'you') out.add('ggym-' + rep); break;
      case 'return-from-graveyard': case 'graveyard-to-battlefield-many': case 'graveyard-to-hand-many': case 'cast-from-graveyard': case 'return-self-graveyard':
        out.add('wgym-' + rep); if (e.to === 'battlefield' || /battlefield/.test(e.kind)) out.add('genmc' + rep); break;
      case 'library-search': if (/\bland\b/i.test(e.text || '') && /onto the battlefield/i.test(e.text || '')) out.add('glfm-' + rep); break;
      case 'extra-land-play': out.add('glfm-' + rep); break;
      case 'no-max-hand-size': out.add('ghsm-1'); break;
      case 'copy-stack': case 'cast-copy': out.add('gcamn' + rep); break;
      case 'extra-combat': out.add('gatm-' + rep); break;
    }
    for (const k of ['effects', 'then', 'else', 'modes', 'options']) if (Array.isArray(e[k])) walk(e[k].flat ? e[k].flat() : e[k]);
  } };
  walk(res.effects);
  return true;
}
// costs of an activated ability ("Sacrifice a creature:", "Discard a card:")
function costGives(cost, out) {
  if (/\bsacrifice (?:a|an|another|two|three|x|one or more) ([^,:]*)/i.test(cost)) { const w = /creature/i.test(RegExp.$1) ? 'c' : 'p'; if (!/\bthis\b|~/.test(RegExp.$1)) { out.add('gscm' + w + '1'); if (w === 'c') out.add('gdymc1'); } }
  if (/\bdiscard (?:a|an|two|x|one or more|your hand)\b/i.test(cost)) out.add('gdcm-1');
  if (/\breturn (?:a|an|another) [^:]*you control to (?:its|their) owner'?s hand\b/i.test(cost)) out.add('gthm' + whatOf(cost) + '1');
}
// Fixed facts for keywords whose game play is a known chain (owner, 13 Nov: web-slinging, ninjutsu ...)
