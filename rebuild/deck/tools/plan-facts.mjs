// Plan facts (roadmap 6b, batch A): for every Commander card, what it does in a game (gives) and what it waits for (wants),
// read by the GAME ENGINE first (src/engine: its trigger matcher and its effect compiler), the Deck Builder's own reader
// (engine/rules.js rrRead) for what the game engine does not read, and a few fixed keyword facts. The Deck Builder reads the
// table (engine/plans.js) to find a deck's enabler -> payoff chains. Design: rebuild/roadmap/6b-design.md.
//
//   node tools/plan-facts.mjs <cards.json.gz> [out=plan-facts.js] [--force] [--stats]
//
// The table is regenerated by tools/build.sh with every build (owner, 16 Nov). It is skipped when nothing it reads changed
// (the card file, src/engine, this script: the fingerprint in the file's first line).
//
// Fact code, 6 characters: kind (g gives, w wants) · event (2) · side (s this card, m yours, t theirs, a anyone) ·
// what (c creature, t token, l land, i instant/sorcery, n noncreature spell, p permanent, - anything) · repeat (1 again and
// again, o once) — then the source in a separate list (e game engine, r Deck Builder reader, k keyword, x text).
// Events: en enters · th returned to hand · fl blinked · ca cast · dy dies · sc sacrificed · tk token made · dc discard ·
// dr draw · hs hand size · ct +1/+1 counters · lg life gained · lf a land enters · gy to / from the graveyard · at attacks.
